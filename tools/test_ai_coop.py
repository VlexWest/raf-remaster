class Emu:
    MEM = 0x20000000
    STACK = 0x22000000

    def __init__(self, image: bytes):
        from unicorn import Uc, UC_ARCH_X86, UC_MODE_32
        from unicorn import x86_const as X
        self.X = X
        u = self.u = Uc(UC_ARCH_X86, UC_MODE_32)
        size = max((len(image) + 0xFFF) & ~0xFFF, 0x1100000 - BASE)
        u.mem_map(BASE, size)
        u.mem_write(BASE, image)
        u.mem_map(self.MEM, 0x200000)
        u.mem_map(self.STACK, 0x10000)
        self.next = self.MEM
        self.R = [X.UC_X86_REG_EAX, X.UC_X86_REG_ECX, X.UC_X86_REG_EDX, X.UC_X86_REG_EBX,
                  X.UC_X86_REG_ESP, X.UC_X86_REG_EBP, X.UC_X86_REG_ESI, X.UC_X86_REG_EDI]

    def alloc(self, size, data=b""):
        a = self.next
        self.next += (size + 0xF) & ~0xF
        self.u.mem_write(a, data + bytes(size - len(data)))
        return a

    def w32(self, a, v):
        self.u.mem_write(a, struct.pack("<I", v & 0xFFFFFFFF))

    def r32(self, a):
        return struct.unpack("<I", self.u.mem_read(a, 4))[0]

    def run(self, start, ends, regs, count=100000, counter=None):
        from unicorn import UC_HOOK_CODE
        u = self.u
        for r in range(8):
            u.reg_write(self.R[r], 0x0BAD0000 + r)
        for r, v in regs.items():
            u.reg_write(self.R[r], v & 0xFFFFFFFF)
        stop = {}

        def hk(uc, addr, size, _):
            if counter is not None and addr in counter:
                counter[addr] += 1
            if addr in ends:
                stop["at"] = addr
                uc.emu_stop()
        h = u.hook_add(UC_HOOK_CODE, hk)
        try:
            u.emu_start(start, 0xFFFFFFF0, count=count)
        finally:
            u.hook_del(h)
        out = [u.reg_read(self.R[r]) for r in range(8)]
        return out, stop.get("at")


EAX, ECX, EDX, EBX, ESP, EBP, ESI, EDI = range(8)
FREED = 0x30000000                  # never mapped in the emulator: stands for freed memory


class World:
    """Players, CPs, combat managers, attack commanders and groups in emulator memory."""

    def __init__(self, e: Emu):
        self.e, self.n = e, 0

    def player(self, ai=True):
        e = self.e
        p = e.alloc(0x1100)
        e.w32(p + P_IDX, self.n)
        self.n += 1
        if ai:
            e.w32(p + P_CP, p)                          # for an AI the CP is the player object
            cm = e.alloc(0x100)
            e.w32(p + CP_CM, cm)
            e.w32(cm + CM_CP, p)
            cmd = e.alloc(0x40)
            e.w32(cm + CM_CMD, cmd)
        return p

    def combat(self, p):
        return self.e.r32(p + CP_CM)

    def stance(self, a, b, v):
        self.e.w32(a + P_STANCE + 4 * self.e.r32(b + P_IDX), v)

    def enemies(self, a, *bs):
        for b in bs:
            self.stance(a, b, 1)

    def allies(self, p, lst):
        e = self.e
        v = e.alloc(4 * max(1, len(lst)), b"".join(struct.pack("<I", x) for x in lst))
        e.w32(p + P_ALLY0, v)
        e.w32(p + P_ALLY1, v + 4 * len(lst))

    def group(self, target, gone=0, units=1):
        e = self.e
        g = e.alloc(0x70)
        u = e.alloc(4 * max(1, units))
        e.w32(g + G_UNITS0, u)
        e.w32(g + G_UNITS1, u + 4 * units)
        e.w32(g + G_TARGET, target)
        e.u.mem_write(g + G_GONE, bytes([gone]))
        return g

    def deque(self, p, groups, off=0, mapsize=None, decoy=None):
        """groups land at k = off .. off+n-1: block k >> 10 (wrapped at mapsize), slot k & 0x3ff.
        decoy: a group placed where an unwrapped block index would read."""
        e = self.e
        cmd = e.r32(self.combat(p) + CM_CMD)
        last = off + len(groups)
        mapsize = mapsize or max(1, (last + 1023) >> 10)
        blocks = [e.alloc(0x1000) for _ in range(mapsize)]
        extra = []
        if decoy is not None:
            extra = [e.alloc(0x1000)]
            for k in range(0x400):
                e.w32(extra[0] + 4 * k, decoy)
        m = e.alloc(4 * (mapsize + len(extra)), b"".join(struct.pack("<I", b) for b in blocks + extra))
        for i, g in enumerate(groups):
            k = off + i
            b = k >> 10
            if b >= mapsize:
                b -= mapsize
            e.w32(blocks[b] + 4 * (k & 0x3FF), g)
        e.w32(cmd + D_MAP, m)
        e.w32(cmd + D_MAPSIZE, mapsize)
        e.w32(cmd + D_OFF, off)
        e.w32(cmd + D_COUNT, len(groups))


def run_store(e: Emu, me, pick):
    """Run the hooked store with eax = pick; -> (stored target, registers ok)."""
    sp = Emu.STACK + 0x8000
    e.u.mem_write(sp, bytes(0x200))
    e.w32(sp + 0x34, e.r32(me + CP_CM))
    regs = {EAX: pick, ESP: sp}
    out, end = e.run(STORE, {STORE_RET}, regs)
    assert end == STORE_RET, hex(end or 0)
    stored = e.r32(sp + 0xEC)
    ok = out[ESP] == sp and all(out[r] == 0x0BAD0000 + r for r in (ECX, EDX, EBX, EBP, ESI, EDI))
    ok &= out[EAX] == stored
    return stored, ok


def emu_ally(patched: bytes):
    e = Emu(patched)
    regs_ok = True

    def case(name, build, want):
        nonlocal regs_ok
        e.next = Emu.MEM
        w = World(e)
        me = w.player()
        pick = w.player(ai=False)                       # the stock choice (an enemy)
        w.enemies(me, pick)
        exp = build(w, me, pick)
        want_v = {"pick": pick}.get(want, exp)
        try:
            got, ok = run_store(e, me, pick)
        except Exception as ex:                         # unicorn: read of unmapped (freed) memory
            check(f"ally-attack: {name}", False, f"fault: {ex}")
            return
        regs_ok &= ok
        check(f"ally-attack: {name}", got == want_v, f"got {got:#x} want {want_v:#x}")

    def no_allies(w, me, pick):
        w.allies(me, [])
    case("no allies -> stock pick", no_allies, "pick")

    def only_self(w, me, pick):
        w.allies(me, [me])
        t = w.player(ai=False)
        w.enemies(me, t)
        w.deque(me, [w.group(t)])                       # my own groups are not an ally's
    case("ally list holds only me -> stock pick", only_self, "pick")

    def human(w, me, pick):
        h = w.player(ai=False)
        w.allies(me, [me, h])
    case("human ally only -> stock pick", human, "pick")

    def joins(w, me, pick):
        a, t = w.player(), w.player(ai=False)
        w.allies(me, [me, a])
        w.enemies(me, t)
        w.deque(a, [w.group(t)])
        return t
    case("AI ally attacks my enemy -> join its target", joins, "t")

    def allied(w, me, pick):
        a, t = w.player(), w.player(ai=False)
        w.allies(me, [a])
        w.stance(me, t, 0)
        w.deque(a, [w.group(t)])
    case("ally target allied to me -> stock pick", allied, "pick")

    def defeated(w, me, pick):
        a, t = w.player(), w.player(ai=False)
        w.allies(me, [a])
        w.enemies(me, t)
        e.u.mem_write(t + P_DEAD, b"\x01")
        w.deque(a, [w.group(t)])
    case("ally target defeated (+0x47f) -> stock pick", defeated, "pick")

    def resigned(w, me, pick):
        a, t = w.player(), w.player(ai=False)
        w.allies(me, [a])
        w.enemies(me, t)
        e.u.mem_write(t + P_RESIGN, b"\x01")
        w.deque(a, [w.group(t)])
    case("ally target resigned (+0x107b) -> stock pick", resigned, "pick")

    def targets_me(w, me, pick):
        a = w.player()
        w.allies(me, [a])
        w.stance(me, me, 1)
        w.deque(a, [w.group(me)])
    case("ally group targets me -> stock pick", targets_me, "pick")

    def disbanded(w, me, pick):
        a, t1, t2 = w.player(), w.player(ai=False), w.player(ai=False)
        w.allies(me, [a])
        w.enemies(me, t1, t2)
        w.deque(a, [w.group(t1, gone=1), w.group(t2)])
        return t2
    case("disbanded group (+0x6e) skipped, next live group wins", disbanded, "t")

    def disbanded_only(w, me, pick):
        a, t1 = w.player(), w.player(ai=False)
        w.allies(me, [a])
        w.enemies(me, t1)
        w.deque(a, [w.group(t1, gone=1), w.group(t1, units=0), w.group(0)])
    case("only disbanded / empty / targetless groups -> stock pick", disbanded_only, "pick")

    def empty(w, me, pick):
        a = w.player()
        w.allies(me, [a])
        w.deque(a, [])
    case("AI ally with empty deque -> stock pick", empty, "pick")

    def no_cm(w, me, pick):
        a = w.player()
        w.allies(me, [a])
        e.w32(a + CP_CM, 0)
    case("AI ally without combat manager -> stock pick, no fault", no_cm, "pick")

    def no_cmd(w, me, pick):
        a = w.player()
        w.allies(me, [a])
        e.w32(w.combat(a) + CM_CMD, 0)
    case("AI ally without attack commander -> stock pick, no fault", no_cmd, "pick")

    def dead_ally(w, me, pick):
        a, t = w.player(), w.player(ai=False)
        w.allies(me, [a])
        w.enemies(me, t)
        e.u.mem_write(a + P_DEAD, b"\x01")
        w.deque(a, [w.group(t)])
    case("defeated AI ally ignored -> stock pick", dead_ally, "pick")

    def wrap(w, me, pick):
        a, t1, t2, d = w.player(), w.player(ai=False), w.player(ai=False), w.player(ai=False)
        w.allies(me, [a])
        w.enemies(me, t1, t2, d)
        # off 2046, map size 2: k 2046/2047 in block 1, k 2048 -> block 2 wraps to block 0 slot 0
        w.deque(a, [w.group(t1, gone=1), w.group(t1, units=0), w.group(t2)], off=2046, mapsize=2,
                decoy=w.group(d))
        return t2
    case("deque wraps past the map end (off 2046, map size 2) -> block 0, not the decoy", wrap, "t")

    def big(w, me, pick):
        a, t1, t2 = w.player(), w.player(ai=False), w.player(ai=False)
        w.allies(me, [a])
        w.enemies(me, t1, t2)
        gs = [w.group(t1, gone=1)] * 1099 + [w.group(t2)]
        w.deque(a, gs, off=1000)
        return t2
    case("1100 groups across three blocks (off 1000) -> the last, only live one", big, "t")

    def two(w, me, pick):
        h, a1, a2, t1, t2 = w.player(ai=False), w.player(), w.player(), w.player(ai=False), w.player(ai=False)
        w.allies(me, [h, me, a1, a2])
        w.enemies(me, t1, t2)
        w.deque(a1, [w.group(t1)])
        w.deque(a2, [w.group(t2)])
        return t1
    case("two AI allies -> first in ally list order wins", two, "t")

    def second(w, me, pick):
        a1, a2, t1, t2 = w.player(), w.player(), w.player(ai=False), w.player(ai=False)
        w.allies(me, [a1, a2])
        w.enemies(me, t2)
        w.stance(me, t1, 0)
        w.deque(a1, [w.group(t1)])
        w.deque(a2, [w.group(t2)])
        return t2
    case("first ally's target allied to me -> second ally's target", second, "t")

    def ai_enemy(w, me, pick):
        a, t = w.player(), w.player()
        w.allies(me, [a])
        w.enemies(me, t)
        w.deque(a, [w.group(t)])
        return t
    case("ally target may be an AI player too", ai_enemy, "t")

    # lifetime paths (docs/ai-coop.md section 6): FREED is unmapped, so any read of it faults
    def stale_dead(w, me, pick):
        a, t = w.player(), w.player(ai=False)
        w.allies(me, [a])
        w.enemies(me, t)
        e.u.mem_write(a + P_DEAD, b"\x01")
        e.w32(a + P_CP, FREED)
    case("defeated ally with a freed CP pointer: flags tested before +0xdf8 is read, no fault", stale_dead, "pick")

    def stale_resigned(w, me, pick):
        a = w.player()
        w.allies(me, [a])
        e.u.mem_write(a + P_RESIGN, b"\x01")
        e.w32(a + P_CP, FREED)
    case("resigned ally with a freed CP pointer: no fault", stale_resigned, "pick")

    def human_garbage(w, me, pick):
        h = w.player(ai=False)
        w.allies(me, [h])
        e.w32(h + CP_CM, FREED)                         # +0xdf8 == 0: nothing behind it is read
    case("human ally (+0xdf8 == 0) with garbage at +0x10e8: not read, no fault", human_garbage, "pick")

    def removed(w, me, pick):
        a, t = w.player(), w.player(ai=False)
        w.enemies(me, t)
        w.deque(a, [w.group(t)])
        w.allies(me, [])                                # RemoveAlly FUN_007b89a0 erased it
    case("ally removed from my ally vector (RemoveAlly): its groups are ignored", removed, "pick")

    def removed_shift(w, me, pick):
        a1, a2, t1, t2 = w.player(), w.player(), w.player(ai=False), w.player(ai=False)
        w.enemies(me, t1, t2)
        w.deque(a1, [w.group(t1)])
        w.deque(a2, [w.group(t2)])
        w.allies(me, [a2])                              # a1 erased, a2 shifted down
        e.w32(a1 + P_CP, FREED)
        return t2
    case("ally erased from the vector front: remaining ally used, erased one never read", removed_shift, "t")

    def reset(w, me, pick):
        a, t = w.player(), w.player(ai=False)
        w.allies(me, [a])
        w.enemies(me, t)
        w.deque(a, [w.group(t)])
        cm = e.alloc(0x100)                             # CP reset FUN_00477c80: fresh combat manager
        e.w32(cm + CM_CP, a)
        e.w32(cm + CM_CMD, e.alloc(0x40))
        e.w32(a + CP_CM, cm)
    case("ally CP reset (new combat manager, empty commander): stock pick", reset, "pick")

    def no_map(w, me, pick):
        a = w.player()
        w.allies(me, [a])
        cmd = e.r32(w.combat(a) + CM_CMD)
        e.w32(cmd + D_MAP, FREED)                       # commander dtor FUN_0048ff80 leaves count 0
        e.w32(cmd + D_COUNT, 0)
    case("commander with count 0 and a freed block map: map not read", no_map, "pick")

    def group_freed_tail(w, me, pick):
        a, t = w.player(), w.player(ai=False)
        w.allies(me, [a])
        w.enemies(me, t)
        w.deque(a, [w.group(t)])
        cmd = e.r32(w.combat(a) + CM_CMD)
        blk = e.r32(e.r32(cmd + D_MAP))
        e.w32(blk + 4, FREED)                           # slot past the count (erased by FUN_0048fa70)
        return t
    case("slot past the deque count holds a freed group: never read", group_freed_tail, "t")

    # control: the harness does catch a read of FREED (live ally whose CP pointer is freed)
    e.next = Emu.MEM
    w = World(e)
    me, pick, a = w.player(), w.player(ai=False), w.player()
    w.allies(me, [a])
    e.w32(a + P_CP, FREED)
    try:
        run_store(e, me, pick)
        faulted = False
    except Exception:
        faulted = True
    check("ally-attack: control: reading FREED faults in the emulator (the cases above prove no read)", faulted)
    check("ally-attack: esp unchanged, ecx/edx/ebx/ebp/esi/edi preserved, eax = stored value", regs_ok)

    st = Emu(STOCK)
    w = World(st)
    me, pick = w.player(), w.player(ai=False)
    got, _ = run_store(st, me, pick)
    check("ally-attack: STOCK store keeps eax (sanity of the harness)", got == pick)


def emu_choice(patched: bytes):
    # weights roll 0x4cf120..0x4cf1fb with a fake Generate: fld dword [value]; ret
    def setup(image):
        e = Emu(image)
        val = e.alloc(4)
        stub = e.alloc(16, b"\xd9\x05" + struct.pack("<I", val) + b"\xc3")
        e.w32(GENERATE, stub)
        rng = e.alloc(0x40)
        e.w32(RNG, rng)
        cp = e.alloc(0x1300)
        e.w32(cp + 0x1238, 70)
        e.w32(cp + 0x123C, 20)
        e.w32(cp + 0x1240, 10)
        files = {}
        for n in ("close", "res", "rev", "fallback"):
            f = e.alloc(0x60)
            files[n] = f
            e.w32(f + 0x50, 0x7000 + len(files))       # file +0x50 = the player (marker values)
        return e, val, stub, cp, files

    names = {0x7001: "close", 0x7002: "res", 0x7003: "rev", 0x7004: "fallback"}

    def roll(env, r, close=True, res=True, rev=True):
        e, val, stub, cp, files = env
        sp = Emu.STACK + 0x8000
        e.u.mem_write(sp, bytes(0x200))
        e.u.mem_write(val, struct.pack("<f", r))
        e.w32(sp + 0x28, cp)
        e.w32(sp + 0x1C, files["close"] if close else 0)
        e.w32(sp + 0x90, 0x7004)
        cnt = {stub: 0}
        out, end = e.run(WEIGHTS, {STORE}, {EBP: files["res"] if res else 0, ESI: files["rev"] if rev else 0,
                                            ESP: sp}, counter=cnt)
        assert end == STORE, hex(end or 0)
        return names.get(out[EAX], hex(out[EAX])), cnt[stub], out[ESP] == sp

    p, s = setup(patched), setup(STOCK)
    rs = [0.0, 0.3, 0.69, 0.71, 0.8, 0.89, 0.91, 0.99]
    got = [roll(p, r) for r in rs]
    check("attack-choice-fix: 70/20/10 -> close <= 0.70 < resource <= 0.90 < revenge",
          [g[0] for g in got] == ["close"] * 3 + ["res"] * 3 + ["rev"] * 2, str([g[0] for g in got]))
    stock = [roll(s, r) for r in rs]
    check("attack-choice-fix: STOCK always picks close", [g[0] for g in stock] == ["close"] * len(rs),
          str([g[0] for g in stock]))
    check("attack-choice-fix: exactly one RNG draw per decision (patched and stock), esp unchanged",
          all(g[1] == 1 and g[2] for g in got + stock))
    got = [roll(p, r, res=False)[0] for r in (0.5, 0.85, 0.95)]
    check("attack-choice-fix: no resource candidate -> close <= 0.90 < revenge (stock fallback order)",
          got == ["close", "close", "rev"], str(got))
    got = [roll(p, r, rev=False)[0] for r in (0.5, 0.75, 0.95)]
    check("attack-choice-fix: no revenge candidate -> close <= 0.70 < resource", got == ["close", "res", "res"],
          str(got))
    got = [roll(p, r, close=False)[0] for r in (0.1, 0.95)]
    check("attack-choice-fix: no close candidate -> resource (stock fallback)", got == ["res", "res"], str(got))
    got = [roll(p, r, close=False, res=False, rev=False)[0] for r in (0.1, 0.95)]
    check("attack-choice-fix: no candidate -> [esp+0x90] (stock fallback)", got == ["fallback", "fallback"],
          str(got))
    e, val, stub, cp, files = p
    e.w32(cp + 0x1238, 20)
    e.w32(cp + 0x123C, 50)
    got = [roll(p, r)[0] for r in (0.19, 0.21, 0.69, 0.71)]
    check("attack-choice-fix: other weights 20/50/30 split at 0.20 / 0.70", got == ["close", "res", "res", "rev"],
          str(got))


