def gen_ally():
    s = Asm(ALLY_CAVE)
    JAE, JB, JE, JNE = 0x73, 0x72, 0x74, 0x75
    s.raw(0x60)                                         # pushad (saved eax at [esp+0x1c])
    s.raw(0x8B, 0x44, 0x24, 0x34 + 0x20)                # mov eax,[esp+0x54]   combat manager
    s.raw(0x8B, 0xA8); s.u32(CM_CP)                     # mov ebp,[eax+0xc0]   me (CP = player)
    s.raw(0x8B, 0xB5); s.u32(P_ALLY0)                   # mov esi,[ebp+0xa74]  ally iterator
    s.jcc8(0xEB, "ally")
    s.label("found")
    s.raw(0x89, 0x44, 0x24, 0x1C)                       # mov [esp+0x1c],eax   new target
    s.label("done")
    s.raw(0x61)                                         # popad
    s.b += bytes.fromhex(STORE_STOCK)                   # mov [esp+0xec],eax
    s.rel32(b"\xe9", STORE_RET)
    s.label("ally")
    s.raw(0x3B, 0xB5); s.u32(P_ALLY1)                   # cmp esi,[ebp+0xa78]
    s.jcc8(JAE, "done")
    s.raw(0x8B, 0x1E)                                   # mov ebx,[esi]
    s.raw(0x83, 0xC6, 0x04)                             # add esi,4
    s.raw(0x85, 0xDB); s.jcc8(JE, "ally")               # test ebx,ebx
    s.raw(0x3B, 0xDD); s.jcc8(JE, "ally")               # cmp ebx,ebp (the list can hold me)
    s.raw(0x80, 0xBB); s.u32(P_DEAD); s.raw(0); s.jcc8(JNE, "ally")
    s.raw(0x80, 0xBB); s.u32(P_RESIGN); s.raw(0); s.jcc8(JNE, "ally")
    s.raw(0x8B, 0x83); s.u32(P_CP)                      # mov eax,[ebx+0xdf8]  0 = human
    s.raw(0x85, 0xC0); s.jcc8(JE, "ally")
    s.raw(0x8B, 0x80); s.u32(CP_CM)                     # mov eax,[eax+0x10e8] combat manager
    s.raw(0x85, 0xC0); s.jcc8(JE, "ally")
    s.raw(0x8B, 0xB8); s.u32(CM_CMD)                    # mov edi,[eax+0xc4]   attack commander
    s.raw(0x85, 0xFF); s.jcc8(JE, "ally")
    s.raw(0x33, 0xC9)                                   # xor ecx,ecx          i
    s.label("grp")
    s.raw(0x3B, 0x4F, D_COUNT); s.jcc8(JAE, "ally")     # cmp ecx,[edi+0x14]
    s.raw(0x8B, 0x47, D_OFF)                            # mov eax,[edi+0x10]
    s.raw(0x03, 0xC1)                                   # add eax,ecx          k = off + i
    s.raw(0x41)                                         # inc ecx
    s.raw(0x8B, 0xD0)                                   # mov edx,eax
    s.raw(0x81, 0xE2); s.u32(0x3FF)                     # and edx,0x3ff
    s.raw(0xC1, 0xE8, 0x0A)                             # shr eax,10           block
    s.raw(0x3B, 0x47, D_MAPSIZE); s.jcc8(JB, "nowrap")  # cmp eax,[edi+0xc]
    s.raw(0x2B, 0x47, D_MAPSIZE)                        # sub eax,[edi+0xc]
    s.label("nowrap")
    s.raw(0x8B, 0x5F, D_MAP)                            # mov ebx,[edi+8]
    s.raw(0x8B, 0x04, 0x83)                             # mov eax,[ebx+eax*4]
    s.raw(0x8B, 0x04, 0x90)                             # mov eax,[eax+edx*4]  group
    s.raw(0x85, 0xC0); s.jcc8(JE, "grp")
    s.raw(0x80, 0x78, G_GONE, 0); s.jcc8(JNE, "grp")    # disbanded
    s.raw(0x8B, 0x50, G_UNITS0)                         # mov edx,[eax+8]
    s.raw(0x85, 0xD2); s.jcc8(JE, "grp")
    s.raw(0x3B, 0x50, G_UNITS1); s.jcc8(JE, "grp")      # no units left
    s.raw(0x8B, 0x40, G_TARGET)                         # mov eax,[eax+0x4c]   target player
    s.raw(0x85, 0xC0); s.jcc8(JE, "grp")
    s.raw(0x3B, 0xC5); s.jcc8(JE, "grp")                # cmp eax,ebp
    s.raw(0x80, 0xB8); s.u32(P_DEAD); s.raw(0); s.jcc8(JNE, "grp")
    s.raw(0x80, 0xB8); s.u32(P_RESIGN); s.raw(0); s.jcc8(JNE, "grp")
    s.raw(0x8B, 0x90); s.u32(P_IDX)                     # mov edx,[eax+0x474]
    s.raw(0x83, 0xBC, 0x95); s.u32(P_STANCE); s.raw(0)  # cmp dword [ebp+edx*4+0xe30],0
    s.jcc8(JE, "grp")                                   # allied to me
    s.rel32(b"\xe9", s.labels["found"])
    return s.finish()


def gen_choice():
    s = Asm(CHOICE_CAVE)
    s.raw(0xFF, 0x15); s.u32(GENERATE)                  # call [URandom::Generate]  r in [0,1)
    s.raw(0xD8, 0x0D); s.u32(CHOICE_DATA)               # fmul dword [100.0]
    s.raw(0xC3)
    return struct.pack("<f", 100.0), s.finish()


def hook(va, op, target, length):
    return (bytes([op]) + struct.pack("<i", target - (va + 5)) + b"\x90" * (length - 5)).hex()


def ally_tuples():
    code = gen_ally()
    return [(EXE, ALLY_CAVE, "00" * len(code), code.hex(), f"ally attack cave ({len(code)} bytes)"),
            (EXE, STORE, STORE_STOCK, hook(STORE, 0xE9, ALLY_CAVE, 7), "attack target: join an AI ally's target")]


def choice_tuples():
    data, code = gen_choice()
    blob = data + code
    return [(EXE, CHOICE_DATA, "00" * len(blob), blob.hex(), f"attack choice cave ({len(blob)} bytes)"),
            (EXE, ROLL, ROLL_STOCK, hook(ROLL, 0xE8, CHOICE_CAVE, 6), "attack choice roll x100")]


FAILED = []


def check(name, cond, extra=""):
    print(("ok   " if cond else "FAIL ") + name + (f"  [{extra}]" if extra and not cond else ""))
    if not cond:
        FAILED.append(name)


def quiet(fn, *a, **k):
    with contextlib.redirect_stdout(io.StringIO()):
        return fn(*a, **k)


MD = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)


def dis(data, va, n):
    o = va - BASE
    return list(MD.disasm(data[o:o + n], va))


def apply_bytes(image: bytes, patches) -> bytes:
    b = bytearray(image)
    for _, va, _old, new, _ in patches:
        raw = bytes.fromhex(new)
        b[va - BASE:va - BASE + len(raw)] = raw
    return bytes(b)


def span(p):
    return p[1], p[1] + len(p[3]) // 2


