"""Offline tests for the click-fix patch (raf_patch.CLICK_FIX). Reads the base install only; never
touches the registry or a running game.

    python tools/test_click_fix.py [stock_game_dir]      (default D:/Games/Rise and Fall)
    python tools/test_click_fix.py --print               print the generated patch tuples

Bug: after launch the game ignores mouse clicks until it is deactivated and reactivated once.
The intro function FUN_00719080 ends with ISMouse/ISKeyboard::Suspend (unacquire, byte +8 = 1).
The main loop entry FUN_00baa8e0 calls Resume once; Resume clears +8 only when the DirectInput
Acquire succeeds, which needs the game window in the foreground (DISCL_FOREGROUND). The per-frame
input function FUN_00ba73e0 skips ISMouse::Refresh while +8 != 0 (0xBA7404), and Refresh is the
only per-frame path that re-acquires, so a failed first Resume leaves the mouse dead until the
window procedure sees a new activation (WM_ACTIVATE/WM_ACTIVATEAPP -> FUN_00ba5610 -> Resume).
ISKeyboard::Refresh has the same +8 gate inside.

Fix: FUN_00ba73e0 jumps into a cave that calls Resume on a suspended keyboard and mouse every
frame. Resume only succeeds when DirectInput grants foreground access, so a game in the background
stays suspended exactly as before. A successful mouse Resume skips the rest of that frame's mouse
update (the stock order: Resume now, Refresh next frame).

1. static: stock bytes, whole instructions, cave in zero .RDATA tail, nothing points into it,
   generated bytes == raf_patch.CLICK_FIX, cave disassembles to the intended code
2. emulation (unicorn) of FUN_00ba73e0 from its entry to the end of the mouse block, against stub
   devices and a stub rasterizer: active, suspended + Resume ok, suspended + Resume refused
   (background), keyboard only; stock bytes as the counter-check (must stay stuck)
"""
import struct
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
REPO = TOOLS.parent
sys.path.insert(0, str(TOOLS))
sys.path.insert(0, str(REPO / "work" / "tools" / "py"))  # capstone, unicorn
import capstone  # noqa: E402

BASE = 0x400000
EXE = "RiseAndFall.exe"
# ---------------------------------------------------------------- addresses (v1.15)
FN = 0xBA73E0           # per-frame input: keyboard Refresh, rasterizer, mouse Refresh + UI update
HOOK = 0xBA73FD         # mov eax,[gISMouse IAT]; mov ecx,[eax]; cmp byte [ecx+8],0; jne 0xBA741D
HOOK_LEN = 13
REFRESH = 0xBA740A      # mov edx,[ecx]; call [edx+0xC]  (ISMouse::Refresh), then UI mouse update
SKIP = 0xBA741D         # after the mouse block
IAT_KBD = 0xC4AC9C      # -> LowLevelEngine gISKeyboard
IAT_MOUSE = 0xC4B498    # -> LowLevelEngine gISMouse
VT_RESUME = 0x10        # ISMouse/ISKeyboard vtable: +0xC Refresh, +0x10 Resume, +0x18 Suspend
CAVE = 0xCE3880         # .RDATA zero tail (zoom-setting uses 0xCE3980..); a stray value in .brick
CAVE_LIMIT = 0xCE3934   # points at 0xCE3934, stay below it


def gen():
    """Cave + hook bytes."""
    c = bytearray()

    def here():
        return CAVE + len(c)

    def rel32(target, end):
        return struct.pack("<i", target - end)

    # keyboard: if suspended, Resume
    c += b"\xa1" + struct.pack("<I", IAT_KBD)          # mov eax,[IAT_KBD]
    c += b"\x8b\x08"                                     # mov ecx,[eax]
    c += b"\x80\x79\x08\x00"                             # cmp byte [ecx+8],0
    c += b"\x74\x05"                                     # je +5 (past the call)
    c += b"\x8b\x11"                                     # mov edx,[ecx]
    c += b"\xff\x52" + bytes([VT_RESUME])                # call [edx+0x10]   ISKeyboard::Resume
    # mouse: active -> stock Refresh path; suspended -> Resume, rest of the frame skipped
    c += b"\xa1" + struct.pack("<I", IAT_MOUSE)        # mov eax,[IAT_MOUSE]
    c += b"\x8b\x08"                                     # mov ecx,[eax]
    c += b"\x80\x79\x08\x00"                             # cmp byte [ecx+8],0
    c += b"\x0f\x84" + rel32(REFRESH, here() + 6)        # je REFRESH
    c += b"\x8b\x11"                                     # mov edx,[ecx]
    c += b"\xff\x52" + bytes([VT_RESUME])                # call [edx+0x10]   ISMouse::Resume
    c += b"\xe9" + rel32(SKIP, here() + 5)               # jmp SKIP
    hook = b"\xe9" + rel32(CAVE, HOOK + 5) + b"\x90" * (HOOK_LEN - 5)
    return bytes(c), hook


def tuples(stock: bytes):
    cave, hook = gen()
    old_hook = stock[HOOK - BASE:HOOK - BASE + HOOK_LEN]
    return [
        (EXE, CAVE, "00" * len(cave), cave.hex(), f"click fix cave ({len(cave)} bytes)"),
        (EXE, HOOK, old_hook.hex(), hook.hex(), "input loop: Resume a suspended mouse/keyboard"),
    ]


FAILED = []


def check(name, cond, extra=""):
    print(("ok   " if cond else "FAIL ") + name + (f"  [{extra}]" if extra and not cond else ""))
    if not cond:
        FAILED.append(name)


MD = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)


def dis(data, va, n):
    o = va - BASE
    return list(MD.disasm(data[o:o + n], va))


def static_checks(stock: bytes):
    import raf_patch as rp
    want = tuples(stock)
    check("raf_patch.CLICK_FIX == generated", [tuple(t[:4]) for t in rp.CLICK_FIX] == [t[:4] for t in want],
          str(rp.CLICK_FIX))
    cave, hook = gen()
    check("cave below limit", CAVE + len(cave) <= CAVE_LIMIT, hex(CAVE + len(cave)))
    check("zoom-setting cave starts after ours", CAVE + len(cave) <= 0xCE3980)
    # .RDATA section, RWX, raw == virtual, zero in stock
    pe = struct.unpack_from("<I", stock, 0x3C)[0]
    nsec = struct.unpack_from("<H", stock, pe + 6)[0]
    opt = struct.unpack_from("<H", stock, pe + 20)[0]
    sec = None
    for i in range(nsec):
        o = pe + 24 + opt + 40 * i
        name = stock[o:o + 8].rstrip(b"\0")
        vs, va, rs, ro = struct.unpack_from("<IIII", stock, o + 8)
        ch = struct.unpack_from("<I", stock, o + 36)[0]
        if va + BASE <= CAVE < va + BASE + rs:
            sec = (name, va, ro, ch)
    check("cave in .RDATA", sec is not None and sec[0] == b".RDATA", str(sec))
    check(".RDATA executable + writable, raw == virtual",
          sec is not None and sec[3] & 0xE0000000 == 0xE0000000 and sec[1] == sec[2])
    check("cave bytes zero in stock", stock[CAVE - BASE:CAVE - BASE + len(cave)] == bytes(len(cave)))
    hits = [hex(i + BASE) for i in range(len(stock) - 3)
            if CAVE <= struct.unpack_from("<I", stock, i)[0] < CAVE + len(cave)]
    check("no 4-byte value in the stock image points into the cave", not hits, ",".join(hits[:5]))
    # hook covers whole stock instructions, exactly the expected ones
    ins = dis(stock, HOOK, HOOK_LEN)
    got = [(i.mnemonic, i.op_str) for i in ins]
    check("stock hook site = mov eax,[IAT_MOUSE]; mov ecx,[eax]; cmp byte [ecx+8],0; jne SKIP",
          got == [("mov", f"eax, dword ptr [{IAT_MOUSE:#x}]"), ("mov", "ecx, dword ptr [eax]"),
                  ("cmp", "byte ptr [ecx + 8], 0"), ("jne", f"{SKIP:#x}")], str(got))
    check("hook ends on an instruction boundary", sum(i.size for i in ins) == HOOK_LEN)
    nxt = dis(stock, REFRESH, 5)
    check("REFRESH = mov edx,[ecx]; call [edx+0xc]",
          [(i.mnemonic, i.op_str) for i in nxt] == [("mov", "edx, dword ptr [ecx]"), ("call", "dword ptr [edx + 0xc]")])
    # nothing jumps into the replaced bytes except at their start
    for i in dis(stock, FN, SKIP + 0x200 - FN):
        if i.mnemonic.startswith("j") and i.op_str.startswith("0x"):
            t = int(i.op_str, 16)
            if HOOK < t < HOOK + HOOK_LEN:
                check(f"no branch into hook site ({i.address:#x})", False)
    kbd = dis(stock, FN, 0x11)
    check("stock FN reads the keyboard through IAT_KBD",
          any(f"[{IAT_KBD:#x}]" in i.op_str for i in kbd))
    # cave disassembles completely
    patched = bytearray(stock)
    patched[CAVE - BASE:CAVE - BASE + len(cave)] = cave
    patched[HOOK - BASE:HOOK - BASE + HOOK_LEN] = hook
    cins = dis(bytes(patched), CAVE, len(cave))
    check("cave disassembles completely", sum(i.size for i in cins) == len(cave))
    for i in cins:
        print(f"      {i.address:08x}: {i.bytes.hex():<14} {i.mnemonic} {i.op_str}")
    return bytes(patched)


# ---------------------------------------------------------------- 2. emulation
class Emu:
    """FUN_00ba73e0 from its entry until SKIP or the UI update, with stub devices + rasterizer."""
    STUB = 0x20000000
    OBJ = 0x21000000
    STACK = 0x22000000

    def __init__(self, image: bytes):
        from unicorn import Uc, UC_ARCH_X86, UC_MODE_32, UC_HOOK_CODE
        from unicorn import x86_const as X
        self.X = X
        u = self.u = Uc(UC_ARCH_X86, UC_MODE_32)
        size = (len(image) + 0xFFF) & ~0xFFF
        size = max(size, 0x1100000 - BASE)
        u.mem_map(BASE, (size + 0xFFF) & ~0xFFF)
        u.mem_write(BASE, image)
        for a in (self.STUB, self.OBJ, self.STACK):
            u.mem_map(a, 0x10000)
        self.calls = []
        self.stubs = {}
        self.foreground = True
        # devices: obj -> vtable with Refresh (+0xC) and Resume (+0x10)
        self.kbd, self.mouse = self.OBJ + 0x100, self.OBJ + 0x200
        for name, obj in (("kbd", self.kbd), ("mouse", self.mouse)):
            vt = obj + 0x80
            u.mem_write(obj, struct.pack("<I", vt))
            for off, fn in ((0xC, "Refresh"), (0x10, "Resume"), (0x18, "Suspend")):
                u.mem_write(vt + off, struct.pack("<I", self.stub(f"{name}.{fn}")))
        # LowLevelEngine globals gISKeyboard/gISMouse and the exe's IAT slots pointing at them
        g = self.OBJ + 0x400
        u.mem_write(g, struct.pack("<II", self.kbd, self.mouse))
        u.mem_write(IAT_KBD, struct.pack("<I", g))
        u.mem_write(IAT_MOUSE, struct.pack("<I", g + 4))
        # rasterizer object at [0x101cbd8], vtable +0x2E0 = UI mouse update; IAT 0xC4CA4C call
        r = self.OBJ + 0x600
        u.mem_write(0x101CBD8, struct.pack("<I", r))
        u.mem_write(r, struct.pack("<I", r + 0x10))
        u.mem_write(r + 0x10 + 0x2E0, struct.pack("<I", self.stub("ui.mouse_update")))
        u.mem_write(0xC4CA4C, struct.pack("<I", self.stub("rast.iat_c4ca4c")))
        u.hook_add(UC_HOOK_CODE, self._on_code, begin=self.STUB, end=self.STUB + 0xFFF)

    def stub(self, name):
        a = self.STUB + 0x10 * len(self.stubs)
        self.stubs[a] = name
        self.u.mem_write(a, b"\xc3")  # thiscall, no args: plain ret
        return a

    def _on_code(self, u, addr, size, _):
        name = self.stubs.get(addr)
        if name is None:
            return
        ecx = u.reg_read(self.X.UC_X86_REG_ECX)
        self.calls.append((name, ecx))
        if name.endswith(".Resume") and self.foreground:  # Acquire granted -> +8 = 0
            u.mem_write(ecx + 8, b"\0")
        for r in (self.X.UC_X86_REG_EAX, self.X.UC_X86_REG_ECX, self.X.UC_X86_REG_EDX):
            u.reg_write(r, 0xDEAD0000)  # volatile registers are garbage after a call

    def run(self, kbd_susp, mouse_susp, foreground):
        X, u = self.X, self.u
        self.calls, self.foreground = [], foreground
        u.mem_write(self.kbd + 8, bytes([kbd_susp]))
        u.mem_write(self.mouse + 8, bytes([mouse_susp]))
        sp = self.STACK + 0x8000
        u.mem_write(sp, struct.pack("<I", 0x0BADF00D))  # return address (never reached)
        u.reg_write(X.UC_X86_REG_ESP, sp)
        u.reg_write(X.UC_X86_REG_ECX, 0x0C0FFEE0)  # this (DAT_0101cb94)
        u.reg_write(X.UC_X86_REG_ESI, 0x51515151)
        u.reg_write(X.UC_X86_REG_EDI, 0xD1D1D1D1)
        u.reg_write(X.UC_X86_REG_EBX, 0xB1B1B1B1)
        u.reg_write(X.UC_X86_REG_EBP, 0xB2B2B2B2)
        u.emu_start(FN, SKIP, count=200)
        end = u.reg_read(X.UC_X86_REG_EIP)
        regs = (u.reg_read(X.UC_X86_REG_ESP), u.reg_read(X.UC_X86_REG_EDI), u.reg_read(X.UC_X86_REG_EBX),
                u.reg_read(X.UC_X86_REG_EBP))
        return dict(end=end, calls=[c[0] for c in self.calls], ecxs=dict((c[0], c[1]) for c in self.calls),
                    kbd8=u.mem_read(self.kbd + 8, 1)[0], mouse8=u.mem_read(self.mouse + 8, 1)[0], regs=regs,
                    sp0=sp)


def emu_checks(stock: bytes, patched: bytes):
    p, s = Emu(patched), Emu(stock)
    # stack after the 3 pushes at the entry: sp0 - 12; edi/ebx/ebp preserved
    def same_regs(r):
        return r["regs"] == (r["sp0"] - 12, 0xD1D1D1D1, 0xB1B1B1B1, 0xB2B2B2B2) and r["end"] == SKIP

    r = p.run(0, 0, True)
    check("active: keyboard + mouse Refresh, UI update, no Resume",
          r["calls"] == ["kbd.Refresh", "rast.iat_c4ca4c", "mouse.Refresh", "ui.mouse_update"], r["calls"])
    check("active: Refresh called on the right objects", r["ecxs"].get("mouse.Refresh") == p.mouse
          and r["ecxs"].get("kbd.Refresh") == p.kbd)
    check("active: stack + callee-saved registers intact", same_regs(r), str(r["regs"]))

    r = p.run(1, 1, True)
    check("suspended, foreground: keyboard + mouse Resume, no mouse Refresh/UI this frame",
          r["calls"] == ["kbd.Refresh", "rast.iat_c4ca4c", "kbd.Resume", "mouse.Resume"], r["calls"])
    check("suspended, foreground: Resume on the right objects",
          r["ecxs"].get("kbd.Resume") == p.kbd and r["ecxs"].get("mouse.Resume") == p.mouse)
    check("suspended, foreground: both devices live again", r["kbd8"] == 0 and r["mouse8"] == 0)
    check("suspended, foreground: stack + registers intact", same_regs(r), str(r["regs"]))
    r2 = p.run(r["kbd8"], r["mouse8"], True)
    check("next frame: back on the stock Refresh path",
          r2["calls"] == ["kbd.Refresh", "rast.iat_c4ca4c", "mouse.Refresh", "ui.mouse_update"], r2["calls"])

    r = p.run(1, 1, False)
    check("suspended, background (Acquire refused): Resume tried, devices stay suspended, no UI update",
          r["calls"] == ["kbd.Refresh", "rast.iat_c4ca4c", "kbd.Resume", "mouse.Resume"]
          and r["kbd8"] == 1 and r["mouse8"] == 1, f'{r["calls"]} {r["kbd8"]} {r["mouse8"]}')
    check("background: stack + registers intact", same_regs(r), str(r["regs"]))

    r = p.run(1, 0, True)
    check("keyboard only suspended: keyboard Resume, mouse on the stock path",
          r["calls"] == ["kbd.Refresh", "rast.iat_c4ca4c", "kbd.Resume", "mouse.Refresh", "ui.mouse_update"],
          r["calls"])
    r = p.run(0, 1, True)
    check("mouse only suspended: mouse Resume only",
          r["calls"] == ["kbd.Refresh", "rast.iat_c4ca4c", "mouse.Resume"], r["calls"])

    # counter-check: the stock code never leaves the suspended state on its own
    r = s.run(1, 1, True)
    check("STOCK suspended + foreground: no Resume, mouse stays dead (the bug)",
          "mouse.Resume" not in r["calls"] and r["mouse8"] == 1 and "ui.mouse_update" not in r["calls"],
          r["calls"])
    check("STOCK active: same calls as patched", s.run(0, 0, True)["calls"] ==
          ["kbd.Refresh", "rast.iat_c4ca4c", "mouse.Refresh", "ui.mouse_update"])


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    game = Path(args[0] if args else "D:/Games/Rise and Fall")
    stock = (game / EXE).read_bytes()
    if "--print" in sys.argv:
        for t in tuples(stock):
            print(f'    ({t[0]!r}, {t[1]:#010x}, "{t[2]}",\n     "{t[3]}",\n     "{t[4]}"),')
        return
    patched = static_checks(stock)
    emu_checks(stock, patched)
    print("ALL CHECKS PASSED" if not FAILED else f"{len(FAILED)} FAILED")
    sys.exit(1 if FAILED else 0)


if __name__ == "__main__":
    main()
