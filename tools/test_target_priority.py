"""Offline tests for the target-priority patch (raf_patch.TARGET_PRIORITY). Reads the base install
only; writes exe copies into a temp folder; never touches the registry or a running game.

    python tools/test_target_priority.py [stock_game_dir]      (default D:/Games/Rise and Fall)
    python tools/test_target_priority.py --print               print the generated patch tuples

Stock targeting (docs/ai.md 1.4): a unit scans the enemies around it and scores each one with the
class row of dbaiunittargeting.dat (class 0 Melee, 1 Short Range, 2 Long Range; the in-memory row
DAT_00d2c960[class] = record bytes 0x6c..0x8c + 0x9c): +0x00 candidate targets me, +0x08 in weapon
range (Short 30, Long 50), +0x0c / +0x10 attack / health compares, +0x20 attack 0, round(+0x1c /
dist^2), round(+0x18 x family multiplier). The best score wins; the scan stops early once a score
reaches +0x24 (Short/Long 15, i.e. the first in-range candidate) or the preferred type +0x14 matches.

The patch adds a family tier bonus for ranged classes (Short/Long; Melee keeps the stock score):
  tier 1 siege (families 30 Ram, 31 Siege 333, 57 Ladder Team, 62 Siege Tower, 63 Siege Building,
  65 Naval Siege, 68 Entrenched Siege), tier 2 archers (29 Human Archer, 14 Mounted Archer,
  54 Cavalry Archer), tier 3 hero (8).
  T_ALL: added to every candidate; T_IN: added on top when the candidate is in weapon range;
  T_IN_G replaces T_IN when the attacker's stance (unit+0x624, pointer into the dbunitbehavior
  vector [0xD2F004]) is Guard (index 2): in-range siege then beats everything else.
  Fire spreading (RAF-10): an in-range candidate gets FREE on top unless 3+ goals of other units
  already aim at it ([unit+0x858]; the attacker's own goal does not count); siege always gets it.
  The early stop threshold of Short/Long rises to STOP so the scan sees every candidate (a Guard
  unit still stops at the first in-range siege). Integer adds only, no floats, no randomness.

Hooked scorers (each: in-range block, end of the score sum; the two scan loops also the stop test):
  FUN_00a8c8c0  unit target scan        ctx esi (+0x24 attacker, +0x58 class), candidate edi, score ebp
  FUN_00a92810  scan over the map grid  attacker ebx, class [ebp+0x14], candidate edi, score esi
  FUN_00935fa0  formation chooser       ctx edi (+0x68 class), attacker ebp, candidate esi, score ebx
Not hooked: FUN_004a27d0 (goal re-scoring with the same table) and FUN_00557450 (goal weight =
3 x threshold; the reason the threshold is raised in the exe, not in dbaiunittargeting.dat).

1. static: stock bytes, whole instructions, no branch into a hook, cave zero / RWX / unreferenced,
   generated bytes == raf_patch.TARGET_PRIORITY, cave disassembles completely
2. emulation (unicorn) of the hooked blocks with fake ctx/unit/def memory
3. apply / re-apply / revert byte-exact on an exe copy, together with click-fix and zoom-setting
"""
