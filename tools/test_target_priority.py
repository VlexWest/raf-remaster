        check(f"{label}: stop test keeps score/ctx registers and stores", all(r[1] for r in res))
        stock = [fn(st, c, v)[0] for c, v in ((1, 14), (1, 15), (2, 15))]
        check(f"{label}: STOCK stops Short/Long at 15", stock == [False, True, True], str(stock))


