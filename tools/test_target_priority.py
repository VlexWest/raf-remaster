def data_bytes() -> bytes:
    d = bytearray()
    for t in (BONUS_ALL, BONUS_IN, BONUS_IN_GUARD):
        for row in t:
            d += bytes(row)
    d += bytes(STOP + [0])
    fam = bytearray(N_FAM)
    for f, tier in FAMILIES.items():
        fam[f] = tier
    d += fam
    assert len(d) == T_FAM - DATA + N_FAM
    return bytes(d)


class Asm:
    def __init__(self, origin):
        self.origin, self.b, self.labels, self.fix = origin, bytearray(), {}, []

    @property
    def here(self):
        return self.origin + len(self.b)

    def label(self, name):
        self.labels[name] = self.here

    def raw(self, *bs):
        self.b += bytes(bs)

    def u32(self, v):
        self.b += struct.pack("<I", v & 0xFFFFFFFF)

    def rel32(self, op: bytes, target):
        self.b += op
        self.u32(target - (self.here + 4))

    def jcc8(self, op, name):
        self.raw(op, 0)
        self.fix.append((len(self.b) - 1, name))

    def finish(self):
        for pos, name in self.fix:
            rel = self.labels[name] - (self.origin + pos + 1)
            assert -128 <= rel < 128, name
            self.b[pos] = rel & 0xFF
        return bytes(self.b)


def modrm_disp8(op, reg, base, disp):
    assert base != ESP and 0 <= disp < 0x80
    return bytes([op, 0x40 | reg << 3 | base, disp])


def gen():
    """(data bytes, code bytes, [(hook va, stock hex, hook hex, note)])"""
    s = Asm(CODE)
    hooks = []
    JA, JAE, JE, JNE, JZ = 0x77, 0x73, 0x74, 0x75, 0x74

    # tier: edx = candidate unit -> eax = tier (0 none); clobbers eax
    s.label("tier")
    s.raw(0x8B, 0x82); s.u32(DEF)                       # mov eax,[edx+0x90]
    s.raw(0x85, 0xC0); s.jcc8(JZ, "tier0")              # test eax,eax; jz
    s.raw(0x8B, 0x80); s.u32(FAMILY)                    # mov eax,[eax+0x220]
    s.raw(0x83, 0xF8, N_FAM); s.jcc8(JAE, "tier0")      # cmp eax,N_FAM; jae
    s.raw(0x0F, 0xB6, 0x80); s.u32(T_FAM)               # movzx eax, byte [eax+T_FAM]
    s.raw(0xC3)
    s.label("tier0")
    s.raw(0x33, 0xC0, 0xC3)                             # xor eax,eax; ret

    # guard: eax = attacker unit -> ZF=1 when its stance is Guard; clobbers eax, edx. +0x624 is only
    # compared, never dereferenced (every scanned attacker is a unit object of >= 0x940 bytes:
    # FUN_00a84e10 reads its +0x93e; towers/buildings carry 0 or a stance pointer there)
    s.label("guard")
    s.raw(0x8B, 0x15); s.u32(BEHAVIORS)                 # mov edx,[BEHAVIORS]
    s.raw(0x85, 0xC0); s.jcc8(JZ, "noguard")            # test eax,eax; jz (no attacker)
    s.raw(0x85, 0xD2); s.jcc8(JZ, "noguard")            # test edx,edx; jz
    s.raw(0x8B, 0x80); s.u32(STANCE)                    # mov eax,[eax+0x624]
    s.raw(0x3B, 0x42, 4 * GUARD)                        # cmp eax,[edx+8]
    s.raw(0xC3)
    s.label("noguard")
    s.raw(0x83, 0xCA, 0x01, 0xC3)                       # or edx,1 (ZF=0); ret

    # stop: edx = class, eax = stock threshold -> eax = threshold; clobbers edx
    s.label("stop")
    s.raw(0x83, 0xFA, 0x02); s.jcc8(JA, "stop_keep")    # cmp edx,2; ja
    s.raw(0x0F, 0xB6, 0x92); s.u32(T_STOP)              # movzx edx, byte [edx+T_STOP]
    s.raw(0x85, 0xD2); s.jcc8(JZ, "stop_keep")          # test edx,edx; jz
    s.raw(0x8B, 0xC2)                                   # mov eax,edx
    s.label("stop_keep")
    s.raw(0xC3)

    # inrange: ecx = class (0..2), edx = candidate, [esp+4] = candidate unit, [esp+8] = attacker
    # -> edx = in-range bonus (T_IN or T_IN_G, + FREE unless saturated); clobbers eax, ecx; ret 8
    s.label("inrange")
    s.rel32(b"\xe8", s.labels["tier"])                  # call tier
    s.raw(0x8D, 0x04, 0x88)                             # lea eax,[eax+ecx*4]
    s.raw(0x50)                                         # push eax
    s.raw(0x8B, 0x44, 0x24, 0x0C)                       # mov eax,[esp+12] (attacker)
    s.rel32(b"\xe8", s.labels["guard"])                 # call guard
    s.raw(0x58)                                         # pop eax
    s.jcc8(JNE, "in_plain")
    s.raw(0x0F, 0xB6, 0x90); s.u32(T_IN_G)              # movzx edx, byte [eax+T_IN_G]
    s.jcc8(0xEB, "in_free")
    s.label("in_plain")
    s.raw(0x0F, 0xB6, 0x90); s.u32(T_IN)                # movzx edx, byte [eax+T_IN]
    s.label("in_free")
    s.raw(0xE3); s.fix.append((len(s.b), "in_ret")); s.raw(0)   # jecxz (Melee: no FREE)
    s.raw(0x83, 0xE0, 0x03)                             # and eax,3 (tier)
    s.raw(0x3C, SIEGE); s.jcc8(JE, "in_add")            # cmp al,SIEGE; je (never saturated)
    s.raw(0x8B, 0x4C, 0x24, 0x04)                       # mov ecx,[esp+4] (candidate unit)
    s.raw(0xE3); s.fix.append((len(s.b), "in_add")); s.raw(0)   # jecxz (no unit: free)
    s.raw(0x83, 0xB9); s.u32(COUNT); s.raw(SATURATED)   # cmp dword [ecx+0x858],3
    s.jcc8(0x72, "in_add")                              # jb (fewer than 3 goals on it)
    s.raw(0x8B, 0x44, 0x24, 0x08)                       # mov eax,[esp+8] (attacker; flags kept)
    s.jcc8(JA, "in_ret")                                # ja (4+: saturated even without mine)
    s.raw(0x85, 0xC0); s.jcc8(JZ, "in_ret")             # test eax,eax; jz
    # exactly 3: is one of them my own goal? EEUGAttackUnit target == candidate unit
    s.raw(0x52, 0x51)                                   # push edx; push ecx
    s.raw(0x6A, 0x00); s.raw(0x68); s.u32(TD_ATTACK); s.raw(0x68); s.u32(TD_GOAL); s.raw(0x6A, 0x00)
    s.raw(0xFF, 0xB0); s.u32(GOAL)                      # push dword [eax+0x608]
    s.rel32(b"\xe8", DYNCAST)                           # call __RTDynamicCast
    s.raw(0x83, 0xC4, 0x14)                             # add esp,0x14
    s.raw(0x59, 0x5A)                                   # pop ecx; pop edx
    s.raw(0x85, 0xC0); s.jcc8(JZ, "in_ret")             # no attack goal: saturated
    s.raw(0x8B, 0x40, GOAL_TARGET)                      # mov eax,[eax+0x40] (FUN_004a19d0)
    s.raw(0x85, 0xC0); s.jcc8(JZ, "in_ret")
    s.raw(0x39, 0x88); s.u32(TARGET_UNIT)               # cmp [eax+0x94],ecx
    s.jcc8(JNE, "in_ret")
    s.label("in_add")
    s.raw(0x83, 0xC2, FREE)                             # add edx,FREE
    s.label("in_ret")
    s.raw(0xC2, 0x08, 0x00)                             # ret 8

    def load_class(site):                               # mov ecx,[base+disp]
        base, disp = site["cls"]
        s.b += modrm_disp8(0x8B, ECX, base, disp)

    def push_operand(op):                               # push reg / push dword [base+disp]
        if op[0] == "mem":
            if op[2] < 0x80:
                s.b += modrm_disp8(0xFF, 6, op[1], op[2])
            else:
                s.raw(0xFF, 0x80 | 6 << 3 | op[1]); s.u32(op[2])
        else:
            s.raw(0x50 + op[1])

    def hook(va, length, target, stock_hex, note):
        h = bytearray(b"\xe9" + struct.pack("<i", target - (va + 5))) + b"\x90" * (length - 5)
        hooks.append((va, stock_hex, bytes(h).hex(), note))

    for name, site in SITES.items():
        tag = name.split()[0]
        cand, score = site["cand"], site["score"]
        # in-range block: stock add of +0x08, then the in-range bonus
        va, n, ret = site["inrange"]
        stock = STOCK[va - BASE:va - BASE + n]
        entry = s.here
        s.b += stock                                    # position independent movs + add
        load_class(site)
        s.raw(0x83, 0xF9, 0x02); s.jcc8(JA, f"{tag}_in_back")   # cmp ecx,2; ja
        s.raw(0x8B, 0xC0 | EDX << 3 | cand)             # mov edx,cand
        push_operand(site["att"])                       # push attacker
        push_operand(site["unit"])                      # push candidate unit
        s.rel32(b"\xe8", s.labels["inrange"])           # call inrange
        s.raw(0x03, 0xC0 | score << 3 | EDX)            # add score,edx
        s.label(f"{tag}_in_back")
        s.rel32(b"\xe9", ret)
        hook(va, n, entry, stock.hex(), f"{name}: in-range bonus")

        # end of the score sum: stock 5 bytes, then T_ALL
        va, ret = site["total"]
        entry = s.here
        s.b += bytes.fromhex(STOCK_TOTAL[va])
        load_class(site)
        s.raw(0x83, 0xF9, 0x02); s.jcc8(JA, f"{tag}_all_back")
        s.raw(0x8B, 0xC0 | EDX << 3 | cand)
        s.rel32(b"\xe8", s.labels["tier"])
        s.raw(0x0F, 0xB6, 0x84, 0x88); s.u32(T_ALL)     # movzx eax, byte [eax+ecx*4+T_ALL]
        s.raw(0x03, 0xC0 | score << 3 | EAX)            # add score,eax
        s.label(f"{tag}_all_back")
        s.rel32(b"\xe9", ret)
        hook(va, 5, entry, STOCK_TOTAL[va], f"{name}: family tier bonus")

    # stop test, unit scan: replaces 0xA8CD90..0xA8CD9F
    entry = s.here
    s.raw(0x8B, 0x56, 0x58)                             # mov edx,[esi+0x58]
    s.raw(0xA1); s.u32(TABLE)                           # mov eax,[TABLE]
    s.raw(0x8B, 0x0C, 0x90)                             # mov ecx,[eax+edx*4]
    s.raw(0x8B, 0x41, 0x24)                             # mov eax,[ecx+0x24]
    s.rel32(b"\xe8", s.labels["stop"])
    s.raw(0x3B, 0xE8)                                   # cmp ebp,eax
    s.rel32(b"\x0f\x8c", A_STOP_SKIP)                   # jl
    s.rel32(b"\xe9", A_STOP_SET)
    hook(SITES["unit scan FUN_00a8c8c0"]["stop"], 5, entry, STOCK_STOP, "unit scan: stop threshold")

    # stop test, grid scan: replaces 0xA92DA5..0xA92DBC
    entry = s.here
    s.raw(0x8B, 0x4D, 0x14)                             # mov ecx,[ebp+0x14]
    s.raw(0xA1); s.u32(TABLE)                           # mov eax,[TABLE]
    s.raw(0x8B, 0x14, 0x88)                             # mov edx,[eax+ecx*4]
    s.raw(0x8B, 0x42, 0x24)                             # mov eax,[edx+0x24]
    s.raw(0x8B, 0xD1)                                   # mov edx,ecx
    s.rel32(b"\xe8", s.labels["stop"])
    s.raw(0x3B, 0xF0)                                   # cmp esi,eax
    s.raw(0x89, 0x7D, 0xF4)                             # mov [ebp-0xc],edi
    s.raw(0x89, 0x75, 0xD8)                             # mov [ebp-0x28],esi
    s.rel32(b"\x0f\x8d", C_STOP_EXIT)                   # jge
    s.rel32(b"\xe9", C_STOP_NEXT)
    hook(SITES["grid scan FUN_00a92810"]["stop"], 5, entry, STOCK_STOP, "grid scan: stop threshold")

    return data_bytes(), s.finish(), hooks


def tuples():
    data, code, hooks = gen()
    out = [(EXE, DATA, "00" * len(data), data.hex(), f"target priority tables ({len(data)} bytes)"),
           (EXE, CODE, "00" * len(code), code.hex(), f"target priority cave ({len(code)} bytes)")]
    out += [(EXE, va, old, new, note) for va, old, new, note in hooks]
    return out


FAILED = []


def check(name, cond, extra=""):
    print(("ok   " if cond else "FAIL ") + name + (f"  [{extra}]" if extra and not cond else ""))
    if not cond:
        FAILED.append(name)


def quiet(fn, *a, **k):
    with contextlib.redirect_stdout(io.StringIO()):
        return fn(*a, **k)


MD = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)


def dis(data, va, n):
    o = va - BASE
    return list(MD.disasm(data[o:o + n], va))


def apply_bytes(image: bytes, patches) -> bytes:
    b = bytearray(image)
    for _, va, _old, new, _ in patches:
        raw = bytes.fromhex(new)
        b[va - BASE:va - BASE + len(raw)] = raw
    return bytes(b)


# ---------------------------------------------------------------- 1. static checks
def static_checks():
    import raf_patch as rp
    want = tuples()
    check("raf_patch.TARGET_PRIORITY == generated",
          [tuple(t[:4]) for t in rp.TARGET_PRIORITY] == [t[:4] for t in want])
    data, code, hooks = gen()
    check("tables end below the stray value 0xCE3C8C", DATA + len(data) <= 0xCE3C8C, hex(DATA + len(data)))
    check("code below its limit 0xCE3E8C", CODE + len(code) <= CODE_LIMIT, hex(CODE + len(code)))
    import zoom_setting as zs
    zs_end = max(p[1] + len(p[3]) // 2 for p in zs.patches() if p[1] >= 0xCE0000)
    check("zoom-setting cave ends before ours", zs_end <= DATA, hex(zs_end))
    cf_end = max(p[1] + len(p[3]) // 2 for p in rp.CLICK_FIX if p[1] >= 0xCE0000)
    check("click-fix cave ends before ours", cf_end <= DATA)
    # .RDATA, RWX, raw == virtual, zero in stock
    pe = struct.unpack_from("<I", STOCK, 0x3C)[0]
    nsec = struct.unpack_from("<H", STOCK, pe + 6)[0]
    opt = struct.unpack_from("<H", STOCK, pe + 20)[0]
    sec = None
    for i in range(nsec):
        o = pe + 24 + opt + 40 * i
        vs, va, rs, ro = struct.unpack_from("<IIII", STOCK, o + 8)
        ch = struct.unpack_from("<I", STOCK, o + 36)[0]
        if va + BASE <= DATA < va + BASE + rs:
            sec = (STOCK[o:o + 8].rstrip(b"\0"), va, ro, ch, rs)
    check("cave in .RDATA", sec is not None and sec[0] == b".RDATA", str(sec))
    check(".RDATA executable + writable, raw == virtual, cave inside it",
          sec is not None and sec[3] & 0xE0000000 == 0xE0000000 and sec[1] == sec[2]
          and CODE + len(code) <= sec[1] + BASE + sec[4])
    dllch = struct.unpack_from("<H", STOCK, pe + 24 + 70)[0]
    check("DllCharacteristics without NX_COMPAT", dllch & 0x100 == 0)
    for lo, n in ((DATA, len(data)), (CODE, len(code))):
        check(f"cave bytes {lo:#x}+{n} zero in stock", STOCK[lo - BASE:lo - BASE + n] == bytes(n))
    hits = []
    for i in range(len(STOCK) - 3):
        v = struct.unpack_from("<I", STOCK, i)[0]
        if DATA <= v < DATA + len(data) or CODE <= v < CODE + len(code):
            hits.append(hex(i + BASE))
    check("no 4-byte value in the stock image points into the cave", not hits, ",".join(hits[:5]))
    # hook sites: stock bytes, whole instructions, no branch into them
    for va, old, new, note in hooks:
        n = len(old) // 2
        check(f"stock bytes at {va:#x} ({note})", STOCK[va - BASE:va - BASE + n].hex() == old)
        ins = dis(STOCK, va, n)
