class Emu:
    MEM = 0x20000000
    STACK = 0x22000000

    def __init__(self, image: bytes):
        from unicorn import Uc, UC_ARCH_X86, UC_MODE_32
        from unicorn import x86_const as X
        self.X = X
        u = self.u = Uc(UC_ARCH_X86, UC_MODE_32)
        size = max((len(image) + 0xFFF) & ~0xFFF, 0x1100000 - BASE)
        u.mem_map(BASE, size)
        u.mem_write(BASE, image)
        u.mem_map(self.MEM, 0x100000)
        u.mem_map(self.STACK, 0x10000)
        self.next = self.MEM
        # dbaiunittargeting rows as the loader builds them (record 0x6c..0x8c, 0x9c)
        rows = []
        for vals in ([2, 1, 50, 1, 1, 0, 1, 50, -500, 50], [15, 20, 30, 6, 6, 0, 1, 2, -500, 15],
                     [10, 15, 50, 4, 4, 0, 1, 0, -500, 15]):
            rows.append(self.alloc(struct.pack("<10i", *vals)))
        u.mem_write(TABLE, struct.pack("<I", self.alloc(struct.pack("<3I", *rows))))
        self.behav = [self.alloc(bytes(0x80)) for _ in range(9)]
        u.mem_write(BEHAVIORS, struct.pack("<I", self.alloc(struct.pack("<9I", *self.behav))))
        # __RTDynamicCast (msvcrt import, not bound here): cdecl stub, returns arg 0 when it is one of
        # the fake EEUGAttackUnit goals and the requested types are EEUnitGoal -> EEUGAttackUnit
        self.attack_goals, self.casts = set(), []
        from unicorn import UC_HOOK_CODE

        def dyncast(uc, addr, size, _):
            esp = uc.reg_read(X.UC_X86_REG_ESP)
            ret, ptr, _vf, src, dst, _rt = struct.unpack("<6I", uc.mem_read(esp, 24))
            self.casts.append((ptr, src, dst))
            ok = ptr in self.attack_goals and (src, dst) == (TD_GOAL, TD_ATTACK)
            uc.reg_write(X.UC_X86_REG_EAX, ptr if ok else 0)
            for r in (X.UC_X86_REG_ECX, X.UC_X86_REG_EDX):    # clobbered like the real call
                uc.reg_write(r, 0xDEAD0000)
            uc.reg_write(X.UC_X86_REG_ESP, esp + 4)
            uc.reg_write(X.UC_X86_REG_EIP, ret)
        u.hook_add(UC_HOOK_CODE, dyncast, begin=DYNCAST, end=DYNCAST)

    def alloc(self, data: bytes, size=None):
        a = self.next
        self.next += ((size or len(data)) + 0xF) & ~0xF
        self.u.mem_write(a, data)
        return a

    def unit(self, family, stance=5, goals=0):
        """goals = [unit+0x858], the number of goals targeting this unit; +0x94 = the unit itself
        (FUN_009f75c0)"""
        d = self.alloc(bytes(0x400))
        self.u.mem_write(d + FAMILY, struct.pack("<i", family))
        un = self.alloc(bytes(0x940))
        self.u.mem_write(un + DEF, struct.pack("<I", d))
        self.u.mem_write(un + STANCE, struct.pack("<I", self.behav[stance]))
        self.u.mem_write(un + TARGET_UNIT, struct.pack("<I", un))
        self.u.mem_write(un + COUNT, struct.pack("<I", goals))
        return un

    def target(self, un, victim, attack=True):
        """un's current goal (+0x608) aims at victim: goal +0x40 -> object whose +0x94 is victim"""
        obj = self.alloc(bytes(0x100))
        self.u.mem_write(obj + TARGET_UNIT, struct.pack("<I", victim))
        goal = self.alloc(bytes(0x80))
        self.u.mem_write(goal + GOAL_TARGET, struct.pack("<I", obj))
        self.u.mem_write(un + GOAL, struct.pack("<I", goal))
        if attack:
            self.attack_goals.add(goal)

    def reg(self, r):
        return {EAX: self.X.UC_X86_REG_EAX, ECX: self.X.UC_X86_REG_ECX, EDX: self.X.UC_X86_REG_EDX,
                EBX: self.X.UC_X86_REG_EBX, ESP: self.X.UC_X86_REG_ESP, EBP: self.X.UC_X86_REG_EBP,
                ESI: self.X.UC_X86_REG_ESI, EDI: self.X.UC_X86_REG_EDI}[r]

    def run(self, start, ends, regs, count=400):
        X, u = self.X, self.u
        for r in range(8):
            u.reg_write(self.reg(r), 0x0BAD0000 + r)
        for r, v in regs.items():
            u.reg_write(self.reg(r), v & 0xFFFFFFFF)
        stop = {}

        def hook(uc, addr, size, _):
            if addr in ends:
                stop["at"] = addr
                uc.emu_stop()
        from unicorn import UC_HOOK_CODE
        h = u.hook_add(UC_HOOK_CODE, hook)
        try:
            u.emu_start(start, 0xFFFFFFF0, count=count)
        finally:
            u.hook_del(h)
        out = {r: u.reg_read(self.reg(r)) for r in range(8)}
        out["end"] = stop.get("at")
        return out


def s32(v):
    return v - (1 << 32) if v & 0x80000000 else v


class Scorer:
    """One scorer's in-range test + in-range block + final sum, on an Emu."""

    def __init__(self, e: Emu, name: str):
        self.e, self.name, self.site = e, name, SITES[name]
        self.ctx = e.alloc(bytes(0x100))
        self.sp = Emu.STACK + 0x8000

    def score(self, cls, attacker, cand, in_range, base=0, mult=0):
        e, site = self.e, self.site
        u = e.u
        f = lambda v: struct.pack("<f", v)
        regs = {}
        name = self.name
        if name.startswith("unit"):
            u.mem_write(self.ctx + 0x58, struct.pack("<I", cls))
            u.mem_write(self.ctx + 0x24, struct.pack("<I", attacker))
            u.mem_write(self.ctx + 0x40, f(100.0))
            u.mem_write(self.sp + 0x2C, f(50.0 if in_range else 400.0))
            tbl = struct.unpack("<I", u.mem_read(TABLE, 4))[0]
            regs = {ESI: self.ctx, EDI: cand, EBP: base, EBX: tbl, ESP: self.sp}
            start, sc = 0xA8CC60, EBP
        elif name.startswith("grid"):
            fr = self.ctx + 0x80
            u.mem_write(fr + 0x14, struct.pack("<I", cls))
            u.mem_write(fr - 0x10, f(100.0))
            u.mem_write(fr - 4, f(50.0 if in_range else 400.0))
            regs = {EBP: fr, EBX: attacker, EDI: cand, ESI: base, ESP: self.sp}
            start, sc = 0xA92CD4, ESI
        else:
            u.mem_write(self.ctx + 0x68, struct.pack("<I", cls))
            u.mem_write(self.ctx + 0x50, f(100.0))
            u.mem_write(self.sp + 0x30, f(50.0 if in_range else 400.0))
            regs = {EDI: self.ctx, EBP: attacker, ESI: cand, EBX: base, ESP: self.sp}
            start, sc = 0x936286, EBX
        r = e.run(start, {site["inrange"][2]}, regs)
        assert r["end"] == site["inrange"][2], (name, r["end"])
        kept = {k: r[k] for k in (EBX, ESI, EDI, EBP, ESP) if k != sc}
        # final sum: eax = rounded family-multiplier term, one pushed float arg on the stack
        regs2 = {k: r[k] for k in (EBX, ESI, EDI, EBP)}
        regs2[EAX] = mult
        regs2[ESP] = self.sp - 4
        r2 = self.e.run(site["total"][0], {site["total"][1]}, regs2)
        assert r2["end"] == site["total"][1], (name, r2["end"])
        ok = r2[ESP] == self.sp and all(r2[k] == regs2[k] for k in (EBX, ESI, EDI, EBP) if k != sc)
        ok &= all(r[k] == v for k, v in kept.items() if k != ESP) and r[ESP] == self.sp
        return s32(r2[sc]), ok


